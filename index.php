          <div>
            <p class="eyebrow">More than postures</p>
            <h2>Yoga is an eight-part path</h2>
          </div>
          <p class="lede">Around two thousand years ago, the <em>Yoga Sutras of Patanjali</em> described yoga as eight interconnected &ldquo;limbs.&rdquo; Physical postures are only the third. Understanding the rest gives your practice depth and direction. <a href="philosophy.html">Read the history &amp; philosophy</a>.</p>
        </div>
        <div class="limbs">
          <div class="limb"><span class="n">1</span><h3>Yama</h3><span class="sk">Ethical restraints</span><p>Non-harming, truthfulness, non-stealing, moderation and non-greed.</p></div>
          <div class="limb"><span class="n">2</span><h3>Niyama</h3><span class="sk">Personal observances</span><p>Cleanliness, contentment, discipline, self-study and surrender.</p></div>
          <div class="limb"><span class="n">3</span><h3>Asana</h3><span class="sk">Posture</span><p>A steady, comfortable seat, later expanded into the poses we practice today.</p></div>
          <div class="limb"><span class="n">4</span><h3>Pranayama</h3><span class="sk">Breath regulation</span><p>Techniques that lengthen, guide and refine the breath.</p></div>
          <div class="limb"><span class="n">5</span><h3>Pratyahara</h3><span class="sk">Turning inward</span><p>Drawing attention away from outer distractions.</p></div>
          <div class="limb"><span class="n">6</span><h3>Dharana</h3><span class="sk">Concentration</span><p>Holding the mind on a single point of focus.</p></div>
          <div class="limb"><span class="n">7</span><h3>Dhyana</h3><span class="sk">Meditation</span><p>Sustained, effortless attention.</p></div>
          <div class="limb"><span class="n">8</span><h3>Samadhi</h3><span class="sk">Absorption</span><p>Complete absorption, the culmination of the path.</p></div>
        </div>
      </div>
    </section>

